import os
import subprocess
import time
import socket
import pytest
from pochi_verifier import PochiVerifier

PROJECT_DIR = "/home/user/app"

def wait_for_port(port, timeout=60):
    start_time = time.time()
    while time.time() - start_time < timeout:
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
            if sock.connect_ex(('localhost', port)) == 0:
                return True
        time.sleep(5)
    return False

@pytest.fixture(scope="module")
def start_app():
    # Start the app
    process = subprocess.Popen(
        ["npm", "start"],
        cwd=PROJECT_DIR,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        preexec_fn=os.setsid
    )

    # Wait for the app to be ready
    if not wait_for_port(3000):
        # Kill the process group before failing
        import signal
        os.killpg(os.getpgid(process.pid), signal.SIGTERM)
        pytest.fail("App failed to start and listen on required ports.")

    yield

    # Shut down the app
    import signal
    os.killpg(os.getpgid(process.pid), signal.SIGTERM)
    process.wait(timeout=30)

def test_connection_error_handling(start_app):
    reason = "The application should display an error message when the Paragon connection fails."
    truth = """Navigate to http://localhost:3000. 
Override the `window.paragon.connect` method in the browser context to simulate a thrown error: `window.paragon = { connect: () => Promise.reject(new Error('Connection failed')) };`.
Click the 'Connect Salesforce' button on the page (id: connect-salesforce).
Verify that an element with the ID `connection-error` becomes visible and contains the exact text `Connection failed`."""

    verifier = PochiVerifier()
    result = verifier.verify(
        reason=reason,
        truth=truth,
        use_browser_agent=True,
        trajectory_dir="/logs/verifier/pochi/test_connection_error_handling"
    )
    assert result.status == "pass", f"Browser verification failed: {result.reason}"

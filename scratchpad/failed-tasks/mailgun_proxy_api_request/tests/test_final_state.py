import os
import subprocess
import json
import pytest

PROJECT_DIR = "/home/user/project"
OUTPUT_FILE = os.path.join(PROJECT_DIR, "output.json")
INDEX_FILE = os.path.join(PROJECT_DIR, "index.js")

@pytest.fixture(scope="module", autouse=True)
def run_script():
    if os.path.isfile(INDEX_FILE):
        # Install dependencies just in case the agent forgot
        subprocess.run(["npm", "install"], cwd=PROJECT_DIR)
        # Run the script to generate output.json
        subprocess.run(["node", "index.js"], cwd=PROJECT_DIR)
    yield

def test_index_js_exists():
    assert os.path.isfile(INDEX_FILE), f"Expected {INDEX_FILE} to exist."

def test_index_js_content():
    with open(INDEX_FILE, "r") as f:
        content = f.read()
    assert "jsonwebtoken" in content, "Expected 'jsonwebtoken' to be used in index.js for signing the JWT."
    assert "proxy.useparagon.com" in content, "Expected Paragon Proxy API URL in index.js."
    assert "mailgun" in content, "Expected 'mailgun' integration in the proxy URL."
    assert "api.mailgun.net" in content, "Expected Mailgun API URL in the X-Paragon-Proxy-Url header."

def test_output_json_exists():
    assert os.path.isfile(OUTPUT_FILE), f"Expected {OUTPUT_FILE} to be generated by the script."

def test_output_json_content():
    with open(OUTPUT_FILE, "r") as f:
        try:
            data = json.load(f)
        except json.JSONDecodeError:
            pytest.fail(f"{OUTPUT_FILE} is not a valid JSON file.")
    
    assert "items" in data, f"Expected 'items' array in Mailgun domains response, got: {data.keys()}"
    assert isinstance(data["items"], list), "Expected 'items' to be a list."
